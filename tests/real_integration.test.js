import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { FocusApiClient, UnauthorizedError } from '../lib/api-client.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const serverScript = path.resolve(__dirname, '../scripts/e2e_server.py');
const workspaceRoot = path.resolve(__dirname, '..');

test('E2E Real Integration: 15-step complete workflow against actual backend', async (t) => {
  const port = 18789;
  const serverProc = spawn('python3', [serverScript], {
    env: {
      ...process.env,
      E2E_PORT: String(port),
      PYTHONPATH: `${workspaceRoot}/_server_copy/venv_packages:${workspaceRoot}/src:${workspaceRoot}/_server_copy/src`
    }
  });

  let pairingCode = null;

  try {
    await new Promise((resolve, reject) => {
      serverProc.stdout.on('data', (data) => {
        const line = data.toString();
        if (line.includes('SERVER_READY:')) {
          pairingCode = line.split('SERVER_READY:')[1].trim();
          resolve();
        }
      });
      serverProc.stderr.on('data', () => {});
      serverProc.on('error', reject);
      serverProc.on('exit', (code) => {
        if (!pairingCode) reject(new Error(`Server exited with code ${code} before ready`));
      });
    });

    assert.ok(pairingCode, 'Pairing code generated by server');

    const client = new FocusApiClient({
      baseUrl: `http://127.0.0.1:${port}/api/focus`
    });

    // Step 1: Start backend & test connection
    const conn = await client.testConnection();
    assert.equal(conn.reachable, true);

    // Step 2 & 3: Pair a test Extension device & receive device token
    const pairRes = await client.pair({
      pairingCode,
      deviceName: 'Integration Test Browser',
      browser: 'Chrome'
    });
    assert.equal(pairRes.success, true);
    assert.ok(pairRes.device_token);
    assert.ok(pairRes.device_id);
    assert.equal(client.deviceToken, pairRes.device_token);

    // Step 4: Retrieve Focus Mode status (focus_active: false)
    const status1 = await client.getStatus();
    assert.equal(status1.success, true);
    assert.equal(status1.focus_active, false);

    // Step 5: Enable Focus Mode across all devices
    const enableRes = await client.enable({ durationMinutes: 25, reason: 'Calculus Session' });
    assert.equal(enableRes.success, true);
    assert.equal(enableRes.focus_active, true);

    // Step 6: Classify a normal website
    const normalVerdict = await client.classifyUrl({ url: 'https://en.wikipedia.org/wiki/Calculus' });
    assert.ok(normalVerdict.action === 'ALLOW' || normalVerdict.action === 'BLOCK');

    // Step 7: Classify a hard-blocked website
    const blockedVerdict = await client.classifyUrl({ url: 'https://chatgpt.com/c/123' });
    assert.equal(blockedVerdict.action, 'BLOCK');

    // Step 8: Request a challenge
    const ch1 = await client.getChallenge();
    assert.ok(ch1.challenge_id);
    assert.ok(ch1.question);
    assert.equal(ch1.expires_in, 120);

    // Step 9: Submit an incorrect answer
    const wrongRes = await client.verifyChallenge({ challengeId: ch1.challenge_id, answer: 999999 });
    assert.equal(wrongRes.success, false);
    assert.equal(wrongRes.correct, false);
    assert.equal(wrongRes.focus_active, true);
    assert.ok(wrongRes.new_challenge);
    const ch2 = wrongRes.new_challenge;

    // Step 10: Verify that the old challenge is invalidated
    let oldInvalidated = false;
    try {
      await client.verifyChallenge({ challengeId: ch1.challenge_id, answer: 999999 });
    } catch (err) {
      oldInvalidated = true;
      assert.equal(err.status, 409);
    }
    assert.equal(oldInvalidated, true, 'Replaying consumed challenge must fail with 409');

    // Step 11: Inspect replacement challenge
    assert.ok(ch2.challenge_id);
    assert.notEqual(ch2.challenge_id, ch1.challenge_id);

    // Step 12: Submit a correct answer to the replacement challenge
    const solRes = await fetch(`http://127.0.0.1:${port}/api/test/solution`);
    const { answer: correctAns } = await solRes.json();
    assert.notEqual(correctAns, null);
    const correctRes = await client.verifyChallenge({ challengeId: ch2.challenge_id, answer: correctAns });
    assert.equal(correctRes.success, true);
    assert.equal(correctRes.correct, true);

    // Step 13: Verify Focus Mode becomes OFF
    assert.equal(correctRes.focus_active, false);
    assert.equal(correctRes.enabled, false);
    const status2 = await client.getStatus();
    assert.equal(status2.focus_active, false);

    // Step 14: Revoke the test device
    const unpairRes = await client.unpair();
    assert.equal(unpairRes.success, true);
    assert.equal(client.deviceToken, null);

    // Step 15: Verify the revoked token can no longer access protected endpoints
    client.setDeviceToken(pairRes.device_token);
    let rejected = false;
    try {
      await client.getStatus();
    } catch (err) {
      rejected = true;
      assert.ok(err instanceof UnauthorizedError || err.status === 401);
    }
    assert.equal(rejected, true, 'Revoked token must be rejected with 401');

  } finally {
    serverProc.kill('SIGINT');
  }
});
